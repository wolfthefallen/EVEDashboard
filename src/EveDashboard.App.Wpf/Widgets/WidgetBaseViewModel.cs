namespace EveDashboard.App.Wpf.Widgets;

using CommunityToolkit.Mvvm.ComponentModel;
using CommunityToolkit.Mvvm.Input;
using EveDashboard.App.Wpf.Widgets.StatConfig;
using EveDashboard.Core.Settings.WidgetStats;

/// <summary>
/// Abstract base for every widget ViewModel in the grid. Provides the
/// <see cref="LastUpdated"/> property bound by <see cref="WidgetBase"/>'s
/// chrome, the <see cref="HideCommand"/> bound by the chrome's <c>x</c>
/// close button, the cog-button + popup surface
/// (<see cref="HasStatConfig"/> / <see cref="StatConfigPopup"/> /
/// <see cref="IsStatConfigOpen"/>) for per-stat customisation, and an abstract
/// <see cref="RefreshAsync"/> hook that derived widgets implement to
/// repopulate their bound state.
/// </summary>
/// <remarks>
/// <para>
/// Inherits INPC plumbing from <c>CommunityToolkit.Mvvm</c>'s
/// <see cref="ObservableObject"/>; derived classes use
/// <c>[ObservableProperty]</c> to declare bound fields. <c>partial</c> is
/// required so the source generator can emit the property bodies.
/// </para>
/// <para>
/// Contract for hide: derived widgets do nothing. <see cref="HideCommand"/>
/// (generated by <c>[RelayCommand]</c>) raises <see cref="HideRequested"/>;
/// the layout coordinator subscribes to that event when it adds a widget to
/// the dashboard layout and unsubscribes on removal / dispose. The widget
/// VM does not know about the layout coordinator — it just announces "the
/// user clicked the x button on me."
/// </para>
/// <para>
/// Contract for stat-config: <see cref="HasStatConfig"/> defaults to
/// false (chrome cog button hidden). Derived widgets that have stats override
/// it to return true and override <see cref="StatConfigPopup"/> to return
/// their popup VM. The chrome <c>Popup.IsOpen</c> is two-way bound to
/// <see cref="IsStatConfigOpen"/>; click-outside (StaysOpen=False) flips it
/// back to false; <see cref="StatConfigPopupViewModel.ShouldClose"/> drives
/// it via the chrome's binding to also close on Apply / explicit Close.
/// </para>
/// </remarks>
public abstract partial class WidgetBaseViewModel : ObservableObject
{
    /// <summary>
    /// Wall-clock instant of the last successful refresh; null until the
    /// widget has refreshed once. Rendered by a dedicated chrome
    /// TextBlock; the <see cref="StatRowAttribute"/> applies because the
    /// popup's hide-only zone surfaces it as a hidable row.
    /// </summary>
    [ObservableProperty]
    [property: StatRow("Last updated", Reorderable = false, DefaultOrder = 9999)]
    private DateTimeOffset? _lastUpdated;

    /// <summary>
    /// Drives the chrome <c>Last updated</c> TextBlock visibility.
    /// True (default) = visible; false = collapsed (user hid it via the
    /// popup's hide-only zone). The chrome's existing null-trigger still
    /// hides the line until <see cref="LastUpdated"/> is non-null on first
    /// refresh.
    /// </summary>
    [ObservableProperty]
    private bool _isLastUpdatedVisible = true;

    /// <summary>
    /// Two-way bound to the chrome cog <c>ToggleButton.IsChecked</c>
    /// and the <c>Popup.IsOpen</c>. Click-outside flips this to false (via
    /// the popup's <c>StaysOpen=False</c>); a successful Apply on the popup
    /// VM also flips this to false (via <see cref="StatConfigPopupViewModel.ShouldClose"/>).
    /// </summary>
    [ObservableProperty]
    private bool _isStatConfigOpen;

    /// <summary>
    /// True iff this widget supports per-stat customisation.
    /// Default false hides the cog button. Derived widgets with stats
    /// override to return true.
    /// </summary>
    public virtual bool HasStatConfig => false;

    /// <summary>
    /// The popup VM bound by the chrome's <c>Popup</c> ContentPresenter.
    /// Default null. Derived widgets with stats construct their
    /// popup VM in their ctor and override this to return it. The chrome
    /// only resolves the binding when <see cref="HasStatConfig"/> = true,
    /// so a null return in that case is a programming error.
    /// </summary>
    public virtual StatConfigPopupViewModel? StatConfigPopup => null;

    /// <summary>
    /// Two-way bound to the chrome's second ("text size") cog
    /// <c>ToggleButton.IsChecked</c> and its <c>Popup.IsOpen</c>. Click-outside
    /// (the popup's <c>StaysOpen=False</c>) and a successful Apply on the popup
    /// VM (via <see cref="TextSizePopupViewModel.ShouldClose"/>) both flip this
    /// back to false.
    /// </summary>
    [ObservableProperty]
    private bool _isTextSizeConfigOpen;

    /// <summary>
    /// True iff this widget supports per-element text sizing (the Reports
    /// table widgets). Default false hides the text-size cog. Derived widgets
    /// override to return true.
    /// </summary>
    public virtual bool HasTextSizeConfig => false;

    /// <summary>
    /// The text-size popup VM bound by the chrome's second
    /// <c>Popup</c> ContentPresenter. Default null. Table widgets construct it in
    /// their ctor and override this to return it. The chrome only resolves the
    /// binding when <see cref="HasTextSizeConfig"/> = true, so a null return in
    /// that case is a programming error.
    /// </summary>
    public virtual TextSizePopupViewModel? TextSizePopup => null;

    /// <summary>
    /// Raised when the user clicks the chrome <c>x</c> button on this widget.
    /// The layout coordinator subscribes when it adds the widget
    /// to the dashboard layout and unsubscribes on removal / dispose; no
    /// other code path raises this event.
    /// </summary>
    public event Action? HideRequested;

    /// <summary>
    /// Refresh the widget's bound state. Derived widgets typically re-query
    /// the stats repository (or a similar read-only data source) and assign
    /// new values to their <c>[ObservableProperty]</c> fields.
    /// </summary>
    /// <param name="ct">Cancellation token.</param>
    public abstract Task RefreshAsync(CancellationToken ct = default);

    /// <summary>
    /// Bound by the <see cref="WidgetBase"/> chrome's <c>x</c> close button.
    /// Raises <see cref="HideRequested"/>; the layout coordinator
    /// translates that into a <c>Hide(descriptor)</c> call that flips the
    /// widget item's <c>IsHidden</c> flag and triggers a layout save.
    /// </summary>
    [RelayCommand]
    private void Hide() => HideRequested?.Invoke();

    /// <summary>
    /// When the popup VM's <see cref="StatConfigPopupViewModel.ShouldClose"/>
    /// flips to true (Apply success or explicit Close), the chrome flips
    /// <see cref="IsStatConfigOpen"/> back to false through this hook. Wired
    /// up by derived widgets in their ctor; called from the popup VM's
    /// <c>PropertyChanged</c> on <c>ShouldClose</c>.
    /// </summary>
    protected void ClosePopupFromVm()
    {
        IsStatConfigOpen = false;
    }

    /// <summary>
    /// When the text-size popup VM's
    /// <see cref="TextSizePopupViewModel.ShouldClose"/> flips to true (Apply
    /// success or explicit Close), the chrome flips
    /// <see cref="IsTextSizeConfigOpen"/> back to false through this hook. Wired
    /// up by the table widgets in their ctor; called from the popup VM's
    /// <c>PropertyChanged</c> on <c>ShouldClose</c>.
    /// </summary>
    protected void CloseTextSizePopupFromVm()
    {
        IsTextSizeConfigOpen = false;
    }
}
